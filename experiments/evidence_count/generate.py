"""Generate independent-report and decisive-report cases for the saved results.

Each case is deterministic and contains its exact posterior. The independent-report
cases use reliabilities {0.52, 0.55, 0.70}, report counts {4, 8, 16, 32, 64},
positive shares {0.25, 0.375, 0.5, 0.625, 0.75} when n times share is an integer,
three domains, two formats, and six seeds. The reference log-odds are
(2k - n) ln(r / (1-r)).

The decisive-report cases use one 99% reliable report among balanced 55% reliable
reports, with controls for position, weak reports alone, and prompt length. Seeds
vary report order, identifiers, and wording. Neutral lines pad shorter prompts to
within 2% of the longest comparable prompt.
"""
import argparse
import hashlib
import json
import math
import random
from pathlib import Path

HERE = Path(__file__).resolve().parent
SPEC = "v3.1"
SEEDS = (3101, 3203, 3307, 3413, 3517, 3623)
R_GRID = (0.52, 0.55, 0.70)
N_GRID = (4, 8, 16, 32, 64)
SHARES = (0.25, 0.375, 0.5, 0.625, 0.75)
E3_N = (5, 9, 17, 33, 65)
E3_WEAK_R, E3_DECISIVE_R = 0.55, 0.99
PAD_TOL = 0.02
E3_PAD_SUFFIX = " (no reliability)"  # E3 report lines carry "(reliability 55%)"; keep note lines of similar length

DOMAINS = {
    "food": dict(item="food batch", pos_state="contaminated", neg_state="clean",
                 reporters="food inspectors", reporter="Inspector", pos="contaminated", neg="clean",
                 note="shift note only"),
    "reviews": dict(item="product", pos_state="good", neg_state="bad",
                    reporters="product reviewers", reporter="Reviewer", pos="recommend", neg="avoid",
                    note="shipping note only"),
    "scanner": dict(item="network session", pos_state="malicious", neg_state="benign",
                    reporters="automated session scanners", reporter="Scanner", pos="malicious", neg="benign",
                    note="uptime note only"),
}
DOMAIN_ORDER = ("food", "reviews", "scanner")

# ---------------------------------------------------------------- normative answers

def posterior(k, n, r):
    """P(YES | k of n reports positive), prior 1/2, symmetric reliability r, conditional independence."""
    assert 0 <= k <= n and 0.5 < r < 1
    z = (2 * k - n) * math.log(r / (1 - r))
    return 1 / (1 + math.exp(-z))


def posterior_brute(k, n, r):
    """Independent check by direct likelihoods (no log-odds shortcut)."""
    like_yes = r ** k * (1 - r) ** (n - k)
    like_no = (1 - r) ** k * r ** (n - k)
    return like_yes / (like_yes + like_no)


def posterior_reports(reports):
    """reports: list of (sign 1/0, reliability). Log-odds sum."""
    z = sum((1 if s else -1) * math.log(r / (1 - r)) for s, r in reports)
    return 1 / (1 + math.exp(-z))


def rng_for(*parts):
    return random.Random(int.from_bytes(hashlib.sha256(repr(parts).encode()).digest()[:8], "big"))


def pct(r):
    return f"{r:.2f} ({round(r * 100)}%)"

# ---------------------------------------------------------------- story templates (same model, 3 wordings)

def e1_story(t, d, r):
    D = DOMAINS[d]
    fmt = dict(D, r=pct(r), R=D["reporters"][0].upper() + D["reporters"][1:])
    if t == 0:
        s = ('There are exactly two possible hidden states: the {item} is {pos_state} (YES) or the {item} is '
             '{neg_state} (NO). Before any reports, each state has prior probability 1/2. {R} each produce one '
             'report. Given the hidden state, the reports are independent of one another, with no shared errors. '
             'Every report has the same symmetric reliability {r}: P(report says "{pos}" | YES) = '
             'P(report says "{neg}" | NO) = {r}. Every report says exactly one of "{pos}" or "{neg}". The reports '
             'below are fictional and were generated under exactly this probability model.')
    elif t == 1:
        s = ('Consider a {item} that is either {pos_state} (call this YES) or {neg_state} (call this NO); a priori '
             'both are equally likely (probability 1/2 each). A group of {reporters} examined it, one report each. '
             'Conditional on the true state, each report is generated independently: there are no common or shared '
             'sources of error. Each report is correct with probability {r} whatever the true state, so '
             'P("{pos}" | YES) = P("{neg}" | NO) = {r}. A report reads either "{pos}" or "{neg}", never anything '
             'else. These reports are simulated from this exact model; they are not real observations.')
    else:
        s = ('Setup (fictional reports, generated by the model described here). Hidden state: YES = the {item} is '
             '{pos_state}; NO = the {item} is {neg_state}. Prior: P(YES) = P(NO) = 1/2. Evidence: one report from '
             'each of several {reporters}; each report is "{pos}" or "{neg}". Reliability is symmetric and '
             'identical for every report: a report matches the true state with probability {r}, i.e. '
             'P("{pos}" | YES) = P("{neg}" | NO) = {r}. Reports are conditionally independent given the state, '
             'and no errors are shared between reports.')
    return s.format(**fmt)


def e3_story(t, d):
    D = DOMAINS[d]
    fmt = dict(D, R=D["reporters"][0].upper() + D["reporters"][1:])
    if t == 0:
        s = ('There are exactly two possible hidden states: the {item} is {pos_state} (YES) or the {item} is '
             '{neg_state} (NO). Before any reports, each state has prior probability 1/2. {R} each produce one '
             'report. Given the hidden state, the reports are independent of one another, with no shared errors. '
             'Each report has its own reliability, printed beside it, and reliability is symmetric: '
             'P(report says "{pos}" | YES) = P(report says "{neg}" | NO) = that report\'s reliability. Every report '
             'says exactly one of "{pos}" or "{neg}". The reports below are fictional and were generated under '
             'exactly this probability model.')
    elif t == 1:
        s = ('Consider a {item} that is either {pos_state} (call this YES) or {neg_state} (call this NO); a priori '
             'both are equally likely (probability 1/2 each). A group of {reporters} examined it, one report each. '
             'Conditional on the true state, each report is generated independently: there are no common or shared '
             'sources of error. Each report is correct with the probability shown next to it, whatever the true '
             'state, so P("{pos}" | YES) = P("{neg}" | NO) = the shown reliability. A report reads either "{pos}" or '
             '"{neg}", never anything else. These reports are simulated from this exact model; they are not real '
             'observations.')
    else:
        s = ('Setup (fictional reports, generated by the model described here). Hidden state: YES = the {item} is '
             '{pos_state}; NO = the {item} is {neg_state}. Prior: P(YES) = P(NO) = 1/2. Evidence: one report from '
             'each of several {reporters}; each report is "{pos}" or "{neg}". Reliability is symmetric and printed '
             'beside each report: a report matches the true state with that probability, i.e. '
             'P("{pos}" | YES) = P("{neg}" | NO) = its reliability. Reports are conditionally independent given the '
             'state, and no errors are shared between reports.')
    return s.format(**fmt)


HEADERS = ("Reports:", "The reports:", "Evidence received:")
PAD_HEADER = "Log notes (these are not reports and carry no information about the state):"


def count_sentence(t, d, n, k, neg_first):
    D = DOMAINS[d]
    a = (f'{k} of the {n} reports say "{D["pos"]}"', f'the other {n - k} say "{D["neg"]}"')
    if neg_first:
        a = (f'{n - k} of the {n} reports say "{D["neg"]}"', f'the other {k} say "{D["pos"]}"')
    joiner = ("; ", " and ", ", while ")[t]
    return a[0] + joiner + a[1] + "."


def report_ids(rng, m):
    return [str(x) for x in rng.sample(range(1000, 10000), m)]


def case_ref(rng):
    return "".join(rng.choice("ABCDEFGHJKLMNPQRSTUVWXYZ23456789") for _ in range(5))


def padding_lines(domain, start, count, suffix=""):
    return [f"Log {start + j}: {DOMAINS[domain]['note']}{suffix}" for j in range(count)]


def pad_to(state, target_len, domain, suffix=""):
    """Append neutral log lines until the state is as close as possible to target_len (must be within 2%)."""
    if abs(len(state) - target_len) <= PAD_TOL * target_len:
        return state, 0
    best = None
    for m in range(1, 400):
        s = state + "\n" + PAD_HEADER + "\n" + "\n".join(padding_lines(domain, 1, m, suffix))
        diff = abs(len(s) - target_len)
        if best is None or diff < best[0]:
            best = (diff, s, m)
        if len(s) > target_len:
            break
    return best[1], best[2]

# ---------------------------------------------------------------- E1

def make_e1(seed_idx, d, n, k, fmt, r):
    seed = SEEDS[seed_idx]
    t = (seed_idx + DOMAIN_ORDER.index(d)) % 3
    D = DOMAINS[d]
    rng = rng_for("e1v31", seed, d, n, k, r)  # shared by both formats: same order/IDs within a seed
    signs = [1] * k + [0] * (n - k)
    rng.shuffle(signs)
    ids = report_ids(rng, n)
    ref = case_ref(rng)
    head = f"Case {ref}. " + e1_story(t, d, r)
    if fmt == "listed":
        evidence = HEADERS[t] + "\n" + "\n".join(
            f"{D['reporter']} {i}: {D['pos'] if s else D['neg']}" for i, s in zip(ids, signs))
    else:
        evidence = HEADERS[t] + " " + count_sentence(t, d, n, k, neg_first=seed_idx >= 3)
    state = head + "\n" + evidence
    return dict(id=f"e1-r{round(r * 100)}-{d}-n{n}-k{k}-{fmt}-s{seed_idx}", exp="e1", spec=SPEC,
                seed=seed, seed_idx=seed_idx, template=t, domain=d, n=n, k=k, share=k / n, r=r, format=fmt,
                signs=signs if fmt == "listed" else None, ids=ids if fmt == "listed" else None,
                state=state, truth=posterior(k, n, r))


def add_e1_padding(cases):
    """Padded copy of the listed state (n < 64), length-matched to the n=64 state (same seed, domain, r, share)."""
    ref = {(c["seed_idx"], c["domain"], c["r"], c["share"]): len(c["state"])
           for c in cases if c["exp"] == "e1" and c["format"] == "listed" and c["n"] == 64}
    for c in cases:
        if c["exp"] == "e1" and c["format"] == "listed":
            target = ref[(c["seed_idx"], c["domain"], c["r"], c["share"])]
            c["state_padded"], c["pad_lines"] = pad_to(c["state"], target, c["domain"])
            c["pad_target_len"] = target

# ---------------------------------------------------------------- E3

def make_e3(seed_idx, d, n, decisive, location, control):
    assert n in E3_N and location in ("early", "late") and control in ("decisive", "weak_only", "padding")
    seed = SEEDS[seed_idx]
    t = (seed_idx + DOMAIN_ORDER.index(d)) % 3
    D = DOMAINS[d]
    rng = rng_for("e3v31", seed, d, n, decisive)  # weak order/IDs shared by early, late, weak-only, padding
    weak = [1] * ((n - 1) // 2) + [0] * ((n - 1) // 2)
    rng.shuffle(weak)
    ids = report_ids(rng, n)
    ref = case_ref(rng)
    weak_reports = [(s, E3_WEAK_R, i) for s, i in zip(weak, ids[1:])]
    dec = (decisive, E3_DECISIVE_R, ids[0])
    if control == "weak_only":
        reports = weak_reports
    elif location == "early":
        reports = [dec] + weak_reports
    else:
        reports = weak_reports + [dec]
    lines = [f"{D['reporter']} {i}: {D['pos'] if s else D['neg']} (reliability {round(r * 100)}%)"
             for s, r, i in reports]
    state = f"Case {ref}. " + e3_story(t, d) + "\n" + HEADERS[t] + "\n" + "\n".join(lines)
    truth = posterior_reports([(s, r) for s, r, _ in reports])
    loc = location if control != "weak_only" else "none"
    return dict(id=f"e3-{d}-n{n}-d{decisive}-{loc}-{control}-s{seed_idx}", exp="e3", spec=SPEC, seed=seed,
                seed_idx=seed_idx, template=t, domain=d, n=n, n_reports=len(reports), decisive=decisive,
                location=loc, control=control, r=E3_WEAK_R, format="listed",
                signs=[s for s, _, _ in reports], rels=[r for _, r, _ in reports], ids=[i for _, _, i in reports],
                state=state, truth=truth)


def add_e3_padding(cases):
    ref = {(c["seed_idx"], c["domain"], c["decisive"], c["location"]): len(c["state"])
           for c in cases if c["exp"] == "e3" and c["control"] == "decisive" and c["n"] == 65}
    for c in cases:
        if c["exp"] == "e3" and c["control"] == "padding":
            target = ref[(c["seed_idx"], c["domain"], c["decisive"], c["location"])]
            c["state"], c["pad_lines"] = pad_to(c["state"], target, c["domain"], E3_PAD_SUFFIX)
            c["pad_target_len"] = target

# ---------------------------------------------------------------- all cases

def e1_cells():
    for n in N_GRID:
        for f in SHARES:
            if abs(n * f - round(n * f)) < 1e-9:
                yield n, int(round(n * f))


def generate():
    cases = []
    for r in R_GRID:
        for si in range(len(SEEDS)):
            for d in DOMAIN_ORDER:
                for n, k in e1_cells():
                    for fmt in ("listed", "count"):
                        cases.append(make_e1(si, d, n, k, fmt, r))
    add_e1_padding(cases)
    for si in range(len(SEEDS)):
        for d in DOMAIN_ORDER:
            for n in E3_N:
                for dec in (1, 0):
                    for loc in ("early", "late"):
                        cases.append(make_e3(si, d, n, dec, loc, "decisive"))
                        if n != 65:
                            cases.append(make_e3(si, d, n, dec, loc, "padding"))
                    cases.append(make_e3(si, d, n, dec, "early", "weak_only"))
    add_e3_padding(cases)
    return cases


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--output", default=str(HERE / "cases.jsonl"))
    a = p.parse_args()
    cs = generate()
    with open(a.output, "w") as f:
        for c in cs:
            f.write(json.dumps(c) + "\n")
    print(f"{len(cs)} cases -> {a.output}")
